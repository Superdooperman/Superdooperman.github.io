// 3x5 bitmap font (ported from v1 Dt); replaces the Google Font so offline works.
// Every glyph is distinct (M3: S had been drawn the same as 5, O the same as 0; test/font.test.mjs).
export const GLYPHS = Object.freeze({
  A: '111101111101101', B: '110101110101110', C: '111100100100111', D: '110101101101110',
  E: '111100110100111', F: '111100110100100', G: '111100101101111', H: '101101111101101',
  I: '111010010010111', J: '001001001101111', K: '101101110101101', L: '100100100100111',
  M: '101111111101101', N: '111101101101101', O: '111101101101111', P: '111101111100100',
  Q: '111101101111001', R: '111101111110101', S: '011100010001110', T: '111010010010010',
  U: '101101101101111', V: '101101101101010', W: '101101111111101', X: '101101010101101',
  Y: '101101111010010', Z: '111001010100111', 0: '010101101101010', 1: '010110010010111',
  2: '111001111100111', 3: '111001111001111', 4: '101101111001001', 5: '111100111001111',
  6: '111100111101111', 7: '111001001001001', 8: '111101111101111', 9: '111101111001111',
  '.': '000000000000010', '-': '000000111000000', '!': '010010010000010', '?': '111001011000010',
  "'": '010010000000000', '"': '101101000000000',
  ':': '000010000010000', '/': '001001010100100', '+': '000010111010000',
  '<': '001010100010001', '>': '100010001010100',
  ',': '000000000010100', // M4: the reveal and Returned lines use commas
});

export function drawText(ctx, text, x, y, color, scale = 1) {
  ctx.fillStyle = color;
  let cx = Math.round(x);
  const cy = Math.round(y);
  for (const ch of String(text)) {
    const g = GLYPHS[ch.toUpperCase()];
    if (g) for (let b = 0; b < 15; b++) if (g[b] === '1') ctx.fillRect(cx + (b % 3) * scale, cy + Math.floor(b / 3) * scale, scale, scale);
    cx += 4 * scale;
  }
}
